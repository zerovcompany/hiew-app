insert into public.shops (name, category, address_hint)
select v.name, v.category, v.address_hint
from (values
  ('Krispy Kreme',        'โดนัท',           'เซ็นทรัล โคราช'),
  ('Auntie Anne''s',      'เพรทเซล/ขนมอบ',   'เซ็นทรัล โคราช'),
  ('Rotiboy',             'โรตีบันกาแฟ',      'เซ็นทรัล โคราช'),
  ('Bake A Wish',         'ชูครีม/เค้ก',       'เซ็นทรัล โคราช'),
  ('BreadTalk',           'ขนมปัง/เบเกอรี่',   'เดอะมอลล์ โคราช'),
  ('Cinnabon',            'ซินนามอนโรล',      'เดอะมอลล์ โคราช'),
  ('Puff & Pie',          'พาย/เอแคลร์',      'เดอะมอลล์ โคราช'),
  ('ศรีวิไลเบเกอรี่',        'ขนมปัง/เบเกอรี่',   'แถวตลาดย่าโม'),
  ('ขนมบ้านคุณแหม่ม',       'เอแคลร์/เค้ก',      'รอบเมืองโคราช'),
  ('หมี่โคราช ปึงหงี่เชียง', 'ของแห้ง/หมี่โคราช', 'รอบเมืองโคราช')
) as v(name, category, address_hint)
where not exists (
  select 1 from public.shops s where lower(s.name) = lower(v.name)
);
